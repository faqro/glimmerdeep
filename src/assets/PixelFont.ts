const CHARS = Object.keys(GLYPHS).join('');

export function registerPixelFont(scene: Phaser.Scene): void {
  const cols = 16;
  const rows = Math.ceil(CHARS.length / cols);
  const cellW = 6;
  const cellH = 8;

  if (scene.textures.exists('pixel_font')) {
    scene.textures.remove('pixel_font');
  }
  const tex = scene.textures.createCanvas('pixel_font', cols * cellW, rows * cellH)!;
  const canvas = tex.getSourceImage() as HTMLCanvasElement;
  const ctx = canvas.getContext('2d')!;
  ctx.imageSmoothingEnabled = false;

  for (let i = 0; i < CHARS.length; i++) {
    const ch = CHARS[i];
    const glyph = GLYPHS[ch];
    const cx = (i % cols) * cellW;
    const cy = Math.floor(i / cols) * cellH;
    for (let y = 0; y < glyph.length; y++) {
      for (let x = 0; x < glyph[y].length; x++) {
        if (glyph[y][x] === '#') {
          ctx.fillStyle = '#ffffff';
          ctx.fillRect(cx + x, cy + y, 1, 1);
        }
      }
    }
  }

  tex.setFilter(Phaser.Textures.FilterMode.NEAREST);
  tex.refresh();

  const config: Phaser.Types.GameObjects.BitmapText.RetroFontConfig = {
    image: 'pixel_font',
    width: cellW,
    height: cellH,
    chars: CHARS,
    charsPerRow: cols,
    lineSpacing: 2,
    'spacing.x': 0,
    'spacing.y': 0,
    'offset.x': 0,
    'offset.y': 0,
  };

  scene.cache.bitmapFont.add('pixel', Phaser.GameObjects.RetroFont.Parse(scene, config));
}

export function addPixelText(
  scene: Phaser.Scene,
  x: number,
  y: number,
  text: string,
  size = 8,
  color = 0xffffff,
  originX = 0,
  originY = 0,
  maxWidth?: number
): Phaser.GameObjects.BitmapText {
  const bt = scene.add
    .bitmapText(Math.round(x), Math.round(y), 'pixel', text, size)
    .setTint(color)
    .setOrigin(originX, originY);
  if (maxWidth) {
    bt.setMaxWidth(maxWidth);
    if (originX === 0.5) bt.setCenterAlign();
  }
  return bt;
}
